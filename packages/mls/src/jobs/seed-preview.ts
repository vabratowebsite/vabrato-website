// Preview seed: prints SQL that loads the FICTIONAL fixtures (dates rebased to
// today) into a database, marked source = 'mock'. Used once for the hosted
// preview project; never for production data. Remove with
// `mls-sync purge --mock --confirm` before the live feed starts.
//
//   pnpm --filter @vabrato/mls exec tsx src/jobs/seed-preview.ts [--public-only] [--publish-placeholders] > seed.sql
//
// --public-only seeds only the IDX tables the public pages read (offices,
// listings, media, open houses), leaving the VOW/FULL tables empty.
// --publish-placeholders also publishes the placeholder agent profiles, city
// guide and posts so preview pages aren't empty. Testimonials stay
// unpublished. content_launch_blockers() reports all of these until real
// content replaces them (S9 launch check).

import { createTestDb } from "@vabrato/db/testing";
import { buildFixtures } from "../fixtures";
import { MockFeed } from "../mock/feed";
import { createMockHandler } from "../mock/handler";
import { clientEventCounter, createClientFromConfig, PgSyncStore, pgliteSql, runReconcile } from "../sync";

// Parents before children. Columns are listed so generated / identity columns are skipped.
const TABLES: { name: string; skip?: string[]; idx: boolean }[] = [
  { name: "mls_offices", idx: true },
  { name: "mls_members", idx: false },
  { name: "mls_listings", idx: true },
  { name: "mls_listing_vow", idx: false },
  { name: "mls_listing_full", idx: false },
  { name: "mls_price_events", skip: ["id"], idx: false },
  { name: "mls_media", idx: true },
  { name: "mls_open_houses", idx: true },
];

export async function seedPreviewSql(
  opts: { now?: Date; publishPlaceholders?: boolean; publicOnly?: boolean } = {},
): Promise<string> {
  const now = opts.now ?? new Date();
  const t = await createTestDb();
  try {
    const feed = new MockFeed(buildFixtures({ now }), now);
    const config = { mode: "mock" as const, officeId: "VABRA", rateLimitPerSec: 1000, photoMode: "hotlink" as const, soldHistoryYears: 3 };
    const events = clientEventCounter();
    const { client } = createClientFromConfig(config, { mock: createMockHandler({ feed }), onEvent: events.onEvent });
    const store = new PgSyncStore(pgliteSql(t.db));
    const run = await runReconcile({ client, store, config, now: () => now, clientEvents: events });
    if (run.status !== "succeeded") throw new Error(`mock reconcile failed: ${run.error}`);

    const out: string[] = [
      "-- FICTIONAL preview data (packages/mls fixtures), source = 'mock'. Generated by src/jobs/seed-preview.ts.",
      "begin;",
      "delete from public.mls_listings where source = 'mock';",
      "delete from public.mls_members where source = 'mock';",
      "delete from public.mls_offices where source = 'mock';",
    ];
    for (const { name, skip = [], idx } of TABLES) {
      if (opts.publicOnly && !idx) continue;
      const cols = (
        await t.query<{ column_name: string }>(
          `select column_name from information_schema.columns where table_schema = 'public' and table_name = $1 order by ordinal_position`,
          [name],
        )
      )
        .map((c) => c.column_name)
        .filter((c) => !skip.includes(c));
      const [{ rows }] = (await t.query<{ rows: unknown }>(`select coalesce(json_agg(x), '[]') as rows from public.${name} x`)) as [
        { rows: unknown },
      ];
      const json = JSON.stringify(rows);
      if (json.includes("$seed$")) throw new Error("unexpected delimiter in seed data");
      const list = cols.map((c) => `"${c}"`).join(", ");
      out.push(`insert into public.${name} (${list}) select ${list} from json_populate_recordset(null::public.${name}, $seed$${json}$seed$);`);
    }
    // One successful run, so mls_last_updated() (MLS-1) has a time.
    out.push(
      `insert into public.mls_sync_runs (kind, status, finished_at, high_water_mark, counts) values ('reconcile', 'succeeded', now(), ${
        run.highWaterMark ? `'${run.highWaterMark}'` : "null"
      }, '{"preview_seed": true}');`,
    );
    if (opts.publishPlaceholders) {
      out.push(
        "update public.agent_profiles set published = true where is_placeholder;",
        "update public.city_guides set published = true where is_placeholder;",
        "update public.posts set published = true, published_at = coalesce(published_at, now()) where is_placeholder;",
      );
    }
    out.push("commit;");
    return out.join("\n") + "\n";
  } finally {
    await t.close();
  }
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  seedPreviewSql({
    publishPlaceholders: process.argv.includes("--publish-placeholders"),
    publicOnly: process.argv.includes("--public-only"),
  }).then(
    (sql) => process.stdout.write(sql),
    (e: unknown) => {
      console.error((e instanceof Error ? e.message : String(e)).split("\n")[0]);
      process.exit(1);
    },
  );
}
