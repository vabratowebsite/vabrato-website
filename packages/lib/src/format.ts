// Display-only date helpers shared by the apps. ISO dates render via UTC so
// the shown day never shifts with the viewer's timezone.

function utc(iso: string): Date {
  const [y, m, d] = iso.split("-").map(Number) as [number, number, number];
  return new Date(Date.UTC(y, m - 1, d));
}

/** "Mar 11, 2026" */
export function fmtLong(iso: string): string {
  return utc(iso).toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    timeZone: "UTC",
  });
}

/** "Wed, Mar 11" */
export function fmtShort(iso: string): string {
  return utc(iso).toLocaleDateString("en-US", {
    weekday: "short",
    month: "short",
    day: "numeric",
    timeZone: "UTC",
  });
}

/** Today as local-calendar ISO yyyy-mm-dd. */
export function todayISO(): string {
  const now = new Date();
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}
